import type { Config } from "./config.js";
import { PATHS, joinPath, type Io } from "./io.js";
import { slug } from "./text.js";
import type { Entry, EntryType } from "./types.js";
import { loadUsage, type UsageMap } from "./usage.js";

const GENERATED = "<!-- Generated by Archivist from .archivist/ledger.jsonl. Do not edit: changes are overwritten. -->";

const scopeLabel = (e: Entry): string => (e.scope?.paths.length ? ` (${e.scope.paths.join(", ")})` : "");

const adrNo = (e: Entry): string => `ADR-${String(e.adr ?? 0).padStart(4, "0")}`;

export const adrPath = (e: Entry): string => joinPath(PATHS.decisions, `${adrNo(e)}-${slug(e.title)}.md`);

/** Stable order: keeps a loaded rule byte-identical between renders when nothing changed (prompt cache). */
const byAge = (a: Entry, b: Entry): number => a.created.localeCompare(b.created) || a.id.localeCompare(b.id);

const oneLine = (s: string): string => s.replace(/\s*\n\s*/g, " ").trim();

/** A decision's first sentence, at most 120 characters: in most decisions that sentence is the rule itself. */
const firstSentence = (s: string): string => {
  const t = oneLine(s);
  const f = t.match(/^(.+?[.!?])(?:\s|$)/)?.[1] ?? t;
  return f.length > 120 ? `${f.slice(0, 119).trimEnd()}…` : f;
};

/** How decisions are written: `full` where they are loaded because they apply, `compact` in the always-loaded rule. */
type Style = "full" | "compact";

const lineOf = (e: Entry, style: Style): string =>
  e.type === "decision"
    ? `- ${adrNo(e)} **${e.title}**: ${style === "compact" ? firstSentence(e.content) : oneLine(e.content)}`
    : `- **${e.title}**: ${oneLine(e.content)}`;

const HEADINGS: [EntryType, string][] = [
  ["command", "## Commands"],
  ["gotcha", "## Gotchas"],
  ["decision", "## Decisions"],
];
const DECISIONS_NOTE = `Each in full, with its reasons: \`${PATHS.decisions}/ADR-NNNN-*.md\`.`;
const TYPE_RANK: Record<EntryType, number> = { command: 0, gotcha: 1, decision: 2, procedure: 3 };

/** How much an entry has earned its place, from what tasks did with it; one that misleads more than it helps ranks last. */
const merit = (e: Entry, usage: UsageMap): number => {
  const u = usage[e.id];
  if (!u) return 0;
  if (u.harmful > u.helpful) return -1 - u.harmful;
  return u.used + u.seen + 2 * u.helpful;
};

export interface Budget {
  lines: number;
  chars: number;
}

/**
 * Fills a rule file within a budget of lines and characters. Which entries get in is decided by merit (then
 * commands before gotchas before decisions); the ones that do are written in a stable order, so the file does not
 * reshuffle between renders. What does not fit stays one `archivist recall` away and is counted, not dropped silently.
 */
const fill = (head: string[], entries: Entry[], budget: Budget, style: Style, usage: UsageMap): { lines: string[]; omitted: number } => {
  const ranked = [...entries].sort((a, b) => merit(b, usage) - merit(a, usage) || TYPE_RANK[a.type] - TYPE_RANK[b.type] || byAge(a, b));
  const kept = new Set<string>();
  const opened = new Set<EntryType>();
  // Room kept for the closing "N more" line.
  let lines = head.length + 2;
  let chars = head.join("\n").length + 80;
  for (const e of ranked) {
    const line = lineOf(e, style);
    const first = !opened.has(e.type);
    const heading = first ? (HEADINGS.find(([t]) => t === e.type)?.[1] ?? "") : "";
    const note = first && e.type === "decision" ? DECISIONS_NOTE : "";
    const addLines = 1 + (first ? 2 : 0) + (note ? 1 : 0);
    const addChars = line.length + 1 + (first ? heading.length + 2 : 0) + (note ? note.length + 1 : 0);
    if (lines + addLines > budget.lines || chars + addChars > budget.chars) continue;
    kept.add(e.id);
    opened.add(e.type);
    lines += addLines;
    chars += addChars;
  }
  const out = [...head];
  for (const [type, heading] of HEADINGS) {
    const items = entries.filter((e) => e.type === type && kept.has(e.id)).sort(byAge);
    if (!items.length) continue;
    out.push("", heading, ...(type === "decision" ? [DECISIONS_NOTE] : []), ...items.map((e) => lineOf(e, style)));
  }
  const omitted = entries.length - kept.size;
  if (omitted) out.push("", `${omitted} more in \`${PATHS.index}\` (run \`archivist recall <query>\`).`);
  return { lines: out, omitted };
};

/** Live entries a rule file shows: active, and not stale (their evidence still exists). */
const live = (entries: Entry[], stale: Set<string>): Entry[] => entries.filter((e) => e.status === "active" && !stale.has(e.id)).sort(byAge);

/** Procedures become skills, never rule lines. */
const ruleEntries = (entries: Entry[], stale: Set<string>): Entry[] => live(entries, stale).filter((e) => e.type !== "procedure");

/** Scoped to paths, decisions included: they load, in full, when the agent works where they apply. */
const isScoped = (e: Entry): boolean => Boolean(e.scope?.paths.length);

/** The always-loaded rule: what applies anywhere in the project. */
export const renderCore = (entries: Entry[], config: Config, stale = new Set<string>(), usage: UsageMap = {}): string => {
  const head = [
    GENERATED,
    "# Project knowledge (Archivist)",
    "",
    "Facts learned in earlier sessions. Prefer them over re-discovering; if one is wrong, say so. Before exploring, try `archivist recall <words>`.",
  ];
  const core = ruleEntries(entries, stale).filter((e) => !isScoped(e));
  return fill(head, core, { lines: config.budgets.coreLines, chars: config.budgets.coreChars }, config.rules.decisions, usage).lines.join("\n") + "\n";
};

/**
 * Entries that only matter for some paths go to their own rule file with `paths:` frontmatter: Claude Code loads
 * it the first time the agent reads or edits a matching file, and not before.
 */
export const groupAreas = (entries: Entry[], stale = new Set<string>()): Map<string, { paths: string[]; items: Entry[] }> => {
  const groups = new Map<string, Entry[]>();
  for (const e of ruleEntries(entries, stale).filter(isScoped)) {
    const key = [...e.scope!.paths].sort().join("\n");
    groups.set(key, [...(groups.get(key) ?? []), e]);
  }
  const areas = new Map<string, { paths: string[]; items: Entry[] }>();
  for (const [key, items] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const paths = key.split("\n");
    const base = slug(paths[0]!.replace(/[*?{].*$/, "").replace(/\/+$/, "") || "area");
    let name = joinPath(PATHS.rulesDir, `${base}.md`);
    for (let i = 2; areas.has(name) || name === PATHS.coreRule; i++) name = joinPath(PATHS.rulesDir, `${base}-${i}.md`);
    areas.set(name, { paths, items });
  }
  return areas;
};

export const renderAreas = (entries: Entry[], config: Config, stale = new Set<string>(), usage: UsageMap = {}): Map<string, string> => {
  const files = new Map<string, string>();
  for (const [name, { paths, items }] of groupAreas(entries, stale)) {
    const head = ["---", "paths:", ...paths.map((p) => `  - ${JSON.stringify(p)}`), "---", GENERATED, `# Project knowledge for ${paths.join(", ")} (Archivist)`];
    files.set(name, fill(head, items, { lines: config.budgets.pathFileLines, chars: config.budgets.pathFileChars }, "full", usage).lines.join("\n") + "\n");
  }
  return files;
};

export const renderIndex = (entries: Entry[], stale = new Set<string>()): string => {
  const active = entries.filter((e) => e.status === "active").sort(byAge);
  const lines = [GENERATED, "# Archivist index", "", "One line per active entry: `id` type (scope): title.", ""];
  for (const e of active) lines.push(`- \`${e.id}\` ${e.type}${scopeLabel(e)}: ${e.title}${stale.has(e.id) ? " ⚠ stale: its evidence is gone" : ""}`);
  const gone = entries.filter((e) => e.status !== "active").length;
  if (gone) lines.push("", `${gone} deprecated entries are kept in the ledger.`);
  return lines.join("\n") + "\n";
};

export const renderAdr = (e: Entry): string => {
  const status = e.status === "active" ? "Accepted" : `Superseded${e.deprecatedReason ? ` (${e.deprecatedReason})` : ""}`;
  const evidence = e.evidence.filter((v) => v.file).map((v) => `- \`${v.file}\`${v.anchor ? ` (${v.anchor})` : ""}`);
  return [
    GENERATED,
    `# ADR-${String(e.adr ?? 0).padStart(4, "0")}: ${e.title}`,
    "",
    `- Status: ${status}`,
    `- Date: ${e.created.slice(0, 10)}`,
    `- Entry: \`${e.id}\``,
    "",
    "## Context",
    "",
    e.rationale ?? "_Not recorded._",
    "",
    "## Decision",
    "",
    e.content,
    ...(evidence.length ? ["", "## Evidence", "", ...evidence] : []),
    "",
  ].join("\n");
};

/** A skill's directory name doubles as its command: ASCII only, else the entry id. */
export const skillPath = (e: Entry): string => {
  const ascii = slug(e.title, 40).replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "").replace(/-{2,}/g, "-");
  return joinPath(PATHS.skillsDir, `archivist-${ascii.length >= 3 ? ascii : e.id}`, "SKILL.md");
};

/** A repeated workflow, as a skill: its name and description sit in every session's skill list, the steps load on use. */
export const renderSkill = (e: Entry): string => {
  const name = skillPath(e).split("/").at(-2)!;
  // The rationale of a procedure is a whole sentence saying when to use it, in the entries' language.
  const description = oneLine(`${e.title.replace(/[.\s]+$/, "")}.${e.rationale ? ` ${e.rationale}` : ""}`);
  return ["---", `name: ${name}`, `description: ${JSON.stringify(description)}`, "---", GENERATED, `# ${e.title}`, "", e.content.trim(), ""].join("\n");
};

/** Every generated file and its content. */
export const renderViews = (entries: Map<string, Entry>, config: Config, stale = new Set<string>(), usage: UsageMap = {}): Map<string, string> => {
  const all = [...entries.values()];
  const views = new Map<string, string>();
  if (config.rules.files) {
    views.set(PATHS.coreRule, renderCore(all, config, stale, usage));
    for (const [path, text] of renderAreas(all, config, stale, usage)) views.set(path, text);
    for (const e of live(all, stale)) if (e.type === "procedure") views.set(skillPath(e), renderSkill(e));
  }
  views.set(PATHS.index, renderIndex(all, stale));
  for (const e of all) if (e.type === "decision" && e.adr) views.set(adrPath(e), renderAdr(e));
  return views;
};

/**
 * Entries whose cited files are all gone: the fact may no longer hold. They leave the rule files (not the
 * ledger) until a file comes back or the entry is updated, so a refactor cannot leave the agent stale advice.
 */
export const findStale = async (io: Io, entries: Map<string, Entry>): Promise<Set<string>> => {
  const stale = new Set<string>();
  for (const e of entries.values()) {
    if (e.status !== "active") continue;
    const files = e.evidence.map((v) => v.file).filter((f): f is string => Boolean(f));
    if (!files.length) continue;
    let any = false;
    for (const f of files) if (await io.exists(f)) any = true;
    if (!any) stale.add(e.id);
  }
  return stale;
};

/** Writes only what changed: a rewrite of a loaded rule reaches the model as a diff, so churn costs context. */
export const writeViews = async (io: Io, views: Map<string, string>): Promise<string[]> => {
  const written: string[] = [];
  for (const [path, text] of views) {
    if ((await io.read(path)) === text) continue;
    await io.write(path, text);
    written.push(path);
  }
  return written;
};

/** Removes generated files no view produces any more (an area emptied, an ADR renamed). Never touches a file it did not write. */
export const pruneViews = async (io: Io, views: Map<string, string>): Promise<string[]> => {
  if (!io.remove) return [];
  const files: string[] = [];
  for (const dir of [PATHS.rulesDir, PATHS.decisions])
    for (const name of await io.list(dir)) if (name.endsWith(".md")) files.push(joinPath(dir, name));
  const skillDirs = (await io.list(PATHS.skillsDir)).filter((d) => d.startsWith("archivist-")).map((d) => joinPath(PATHS.skillsDir, d));
  for (const dir of skillDirs) files.push(joinPath(dir, "SKILL.md"));

  const removed: string[] = [];
  for (const path of files) {
    if (views.has(path) || !(await io.exists(path))) continue;
    if (!((await io.read(path)) ?? "").slice(0, 600).includes(GENERATED)) continue;
    await io.remove(path);
    removed.push(path);
  }
  // A skill is a directory: once its generated SKILL.md is gone (now or by an earlier version), the emptied
  // directory goes too. One that still holds a file someone added stays.
  for (const dir of skillDirs) {
    if (views.has(joinPath(dir, "SKILL.md")) || (await io.exists(joinPath(dir, "SKILL.md")))) continue;
    if (!io.removeEmptyDir || (await io.list(dir)).length) continue;
    await io.removeEmptyDir(dir);
    removed.push(`${dir}/`);
  }
  return removed;
};

/** Stale check, render, write, prune: what every writer of the ledger runs after it. */
export const renderAll = async (io: Io, entries: Map<string, Entry>, config: Config): Promise<{ written: string[]; removed: string[]; stale: Set<string> }> => {
  const stale = await findStale(io, entries);
  const views = renderViews(entries, config, stale, await loadUsage(io));
  return { written: await writeViews(io, views), removed: await pruneViews(io, views), stale };
};
