import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { PATHS, withLocalIgnored, type Io } from "../core/io.js";

export const nodeIo = (root: string): Io => withLocalIgnored(rawNodeIo(root));

const rawNodeIo = (root: string): Io => ({
  root,
  async read(p) {
    try {
      return await readFile(join(root, p), "utf8");
    } catch {
      return undefined;
    }
  },
  async write(p, text) {
    await mkdir(dirname(join(root, p)), { recursive: true });
    await writeFile(join(root, p), text);
  },
  async exists(p) {
    return existsSync(join(root, p));
  },
  async list(dir) {
    try {
      return await readdir(join(root, dir));
    } catch {
      return [];
    }
  },
  async remove(p) {
    await rm(join(root, p), { force: true });
  },
  async removeEmptyDir(p) {
    await rmdir(join(root, p)).catch(() => undefined);
  },
});

/** The project root: the nearest ancestor with .git or .archivist, else the start directory. */
export const findRoot = (start: string): string => {
  let dir = resolve(start);
  for (;;) {
    if (existsSync(join(dir, ".git")) || existsSync(join(dir, ".archivist"))) return dir;
    const up = dirname(dir);
    if (up === dir) return resolve(start);
    dir = up;
  }
};

const GENERATED_MARK = "Generated by Archivist";

/** Removes what Archivist generated, file by file: anything without its mark (a hand-written rule) stays. */
export const uninstall = async (root: string, purge: boolean): Promise<string[]> => {
  const removed: string[] = [];
  const dropIfGenerated = async (rel: string) => {
    const text = await readFile(join(root, rel), "utf8").catch(() => undefined);
    if (text === undefined || !text.slice(0, 600).includes(GENERATED_MARK)) return;
    await rm(join(root, rel), { force: true });
    removed.push(rel);
  };
  const names = async (rel: string) => readdir(join(root, rel)).catch(() => [] as string[]);
  for (const n of await names(PATHS.rulesDir)) if (n.endsWith(".md")) await dropIfGenerated(`${PATHS.rulesDir}/${n}`);
  for (const d of await names(PATHS.skillsDir)) {
    if (!d.startsWith("archivist-")) continue;
    await dropIfGenerated(`${PATHS.skillsDir}/${d}/SKILL.md`);
    await rmdir(join(root, PATHS.skillsDir, d)).catch(() => undefined);
  }
  // Only empty directories go: rmdir refuses a directory that still holds something.
  await rmdir(join(root, PATHS.rulesDir)).catch(() => undefined);
  if (purge && existsSync(join(root, PATHS.dir))) {
    await rm(join(root, PATHS.dir), { recursive: true, force: true });
    removed.push(`${PATHS.dir}/`);
  }
  return removed;
};
